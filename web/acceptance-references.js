function acceptanceReference(source) {
  const id = new URL(source.url).pathname.split('/').filter(Boolean).pop();
  const record = acceptanceReferences.find(item => item.id === id);
  if (!record) return { ...source, title: source.label, kind: '待核对资料', authors: '', venue: '来源信息待核对' };
  const kind = record.source === 'PPR' ? '预印本' : record.pubTypeList?.pubType.includes('Review') ? '综述论文' : '期刊论文';
  const names = record.authorString.replace(/\.$/, '').split(', ');
  const authors = names.length > 3 ? names.slice(0, 3).join(', ') + ', et al.' : record.authorString;
  const journal = record.journalInfo;
  const venue = [journal?.journal.title || record.bookOrReportDetails?.publisher, record.pubYear, journal?.volume ? journal.volume + (journal.issue ? '(' + journal.issue + ')' : '') : ''].filter(Boolean).join(' · ');
  return { ...source, title: record.title, kind, authors, venue, doi: record.doi };
}
showSources = function(filter = '全部') {
  state.sourceFilter = filter;
  const all = state.sources.map(acceptanceReference);
  const names = ['全部', ...new Set(all.map(item => item.kind))];
  setIndex(names.map(title => ({title})), names.indexOf(filter), item => showSources(item.title));
  const selected = filter === '全部' ? all : all.filter(item => item.kind === filter);
  byId('content-panel').innerHTML = '<div class="source-grid"><div class="source-summary"><span class="reference-eyebrow">研究依据 · 可追溯阅读</span><h1>引用与图源</h1><p>' + all.length + ' 篇文献 · 关联本轮内容页</p><p class="reference-scope">本轮无实际图片或专利；预印本单独标识。</p></div>' + selected.map(source => {
    const used = state.slidePages.flatMap((page, index) => (page.blocks['来源'] || '').includes('](' + source.url + ')') ? [{number: page.number, index}] : []);
    return '<article class="source-card"><div class="reference-topline"><span class="reference-number">' + String(all.indexOf(source) + 1).padStart(2, '0') + '</span><span class="source-kind">' + escapeHtml(source.kind) + '</span><div class="reference-usage"><span>引用于</span>' + used.map(page => '<button type="button" data-reference-page="' + page.index + '">第 ' + page.number + ' 页</button>').join('') + '</div></div><h2>' + escapeHtml(source.title) + '</h2><p class="reference-authors">' + escapeHtml(source.authors) + '</p><p class="reference-venue">' + escapeHtml(source.venue) + '</p><div class="reference-footer">' + (source.doi ? '<div class="reference-doi"><span>DOI: ' + escapeHtml(source.doi) + '</span><button type="button" class="doi-copy" data-doi="' + escapeHtml(source.doi) + '" aria-label="复制 DOI：' + escapeHtml(source.doi) + '">复制</button></div>' : '') + '<a href="' + escapeHtml(source.url) + '" target="_blank" rel="noopener noreferrer">查看原文 ↗</a></div></article>';
  }).join('') + '</div>';
  byId('content-panel').querySelectorAll('[data-reference-page]').forEach(button => button.addEventListener('click', () => {
    state.selectedSlide = Number(button.dataset.referencePage);
    showView('slides');
  }));
  byId('content-panel').querySelectorAll('[data-doi]').forEach(button => button.addEventListener('click', async () => {
    await copyText(button.dataset.doi, 'DOI 已复制。');
  }));
};
